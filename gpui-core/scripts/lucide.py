"""Vendors Lucide's icons: python3 -I scripts/lucide.py <unzipped lucide-icons-X.zip> <version>

Copies each icons/*.svg into assets/lucide with its whitespace collapsed, and writes
src/icon/lucide.rs: every icon's name, its bytes, and an IconName constant for it. Run from
gpui-core/. Lucide is ISC-licensed; its licence is in ../NOTICE.
"""

import pathlib
import re
import sys

src = pathlib.Path(sys.argv[1]) / "icons"
version = sys.argv[2]
out = pathlib.Path("assets/lucide")
out.mkdir(parents=True, exist_ok=True)
for old in out.glob("*.svg"):
    old.unlink()

names = []
# Sorted by name, as IconName::named searches them (not by file name: "mail-check.svg"
# sorts before "mail.svg", but "mail" before "mail-check").
for svg in sorted(src.glob("*.svg"), key=lambda p: p.stem):
    name = svg.stem
    if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", name):
        raise SystemExit(f"unexpected icon name: {name}")
    text = svg.read_text()
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    text = re.sub(r"\s+", " ", text).replace("> <", "><").replace(" />", "/>").strip()
    if "<script" in text or "href" in text:
        raise SystemExit(f"unexpected content in {name}")
    (out / f"{name}.svg").write_text(text + "\n")
    names.append(name)


def camel(name):
    parts = name.split("-")
    s = "".join(p[:1].upper() + p[1:] for p in parts)
    return s if s[0].isalpha() else "I" + s


lines = [
    f"// Generated by scripts/lucide.py from Lucide {version}. Don't edit.",
    "",
    f'/// The Lucide release these icons come from.',
    f'pub const LUCIDE_VERSION: &str = "{version}";',
    "",
    "/// Every icon, sorted by name, with its SVG.",
    "pub(crate) static ICONS: &[(&str, &[u8])] = &[",
]
for n in names:
    lines.append(f'    ("{n}", include_bytes!("../../assets/lucide/{n}.svg")),')
lines += ["];", ""]

# Lucide's old names for its icons (from each icon's metadata), which lucide-react still takes and
# so agents still write: each to its icon, sorted, leaving out any that is an icon's own name.
import json
known = set(names)
aliases = {}
for n in names:
    meta = src / f"{n}.json"
    if not meta.exists():
        continue
    for a in json.loads(meta.read_text()).get("aliases", []):
        a = a["name"] if isinstance(a, dict) else a
        if re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", a) and a not in known:
            aliases.setdefault(a, n)
lines.append("/// Old names, each with the icon it's now called, sorted by old name.")
lines.append("pub(crate) static ALIASES: &[(&str, &str)] = &[")
for a in sorted(aliases):
    lines.append(f'    ("{a}", "{aliases[a]}"),')
lines += ["];", "", "#[allow(non_upper_case_globals)]", "impl super::IconName {"]
seen = set()
for n in names:
    c = camel(n)
    if c in seen:
        raise SystemExit(f"two icons named {c}")
    seen.add(c)
    lines.append(f'    pub const {c}: Self = Self("{n}");')
lines += ["}", ""]
pathlib.Path("src/icon/lucide.rs").write_text("\n".join(lines))
print(f"{len(names)} icons, {len(aliases)} old names")
