// Three slides in view at once, looping round at the ends.
Carousel::new("more-numbers")
    .accessibility_label("More numbers")
    .w(rems(28.))
    .slides_per_view(3)
    .looping(true)
    .children((1..=8).map(|i| {
        div()
            .h(rems(8.))
            .flex()
            .items_center()
            .justify_center()
            .rounded(cx.theme().radius_lg())
            .border_1()
            .border_color(cx.theme().border)
            .bg(cx.theme().card)
            .text_size(cx.theme().text.xl)
            .font_weight(FontWeight::SEMIBOLD)
            .child(format!("{i}"))
    }))
